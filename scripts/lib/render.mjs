                  <div class="flow-row"><span class="flow-label">Sequential</span><span class="flow-step">A</span><span class="flow-arrow" aria-hidden="true">→</span><span class="flow-step">B</span><span class="flow-arrow" aria-hidden="true">→</span><span class="flow-step">C</span></div>
