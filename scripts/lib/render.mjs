/**
 * @param {string} eyebrow @param {string} title @param {string} [text] @param {string} [cls]
 */
export function sectionHeader(eyebrow, title, text, cls = '') {
  return `          <div class="section-header ${cls} reveal">
            <span class="eyebrow">${esc(eyebrow)}</span>
            <h2>${esc(title)}</h2>${text ? `\n            <p>${esc(text)}</p>` : ''}
          </div>`;
}

/** @param {{ name: string, url: string, description: string | null, language: string | null, stars: number | null, note?: string }} r */
function repoCard(r) {
  const meta = [r.language ? `<span>${esc(r.language)}</span>` : '', typeof r.stars === 'number' ? `<span class="repo-stars">${icon('star', 'icon icon-xs')} ${r.stars}</span>` : '']
    .filter(Boolean)
    .join('');
  return `            <article class="card repo-card reveal">
              <div class="repo-head">${icon('github', 'icon')}<h3><a href="${r.url}" ${ext}>${esc(r.name)}</a></h3></div>
              ${r.description ? `<p class="repo-desc">${esc(r.description)}</p>` : ''}
              ${r.note ? `<p class="repo-note">${esc(r.note)}</p>` : ''}
              ${meta ? `<div class="repo-meta">${meta}</div>` : ''}
            </article>`;
}

/** @param {any} data @param {any} repos */
function repositoriesSection(data, repos) {
  const list = repos.repos.length
    ? `          <div class="grid grid-2">\n${repos.repos.map(repoCard).join('\n')}\n          </div>`
    : `          <p class="empty">No public repositories to show yet.</p>`;
  return `      <section class="section" id="repositories">
        <div class="container">
${sectionHeader('GitHub', 'Repositories', 'Public repositories on my GitHub profile. Names, descriptions and stats come from the GitHub API.')}
${list}
          <p class="fine-print">Last refreshed ${esc(repos.fetchedAt)}. <a href="${data.site.github}" ${ext}>See everything on GitHub ${icon('arrow-up-right', 'icon icon-xs')}</a></p>
        </div>
      </section>`;
}

