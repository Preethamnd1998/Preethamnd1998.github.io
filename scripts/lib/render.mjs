// Renders every page from data/site.json and data/repos.json. Pure: no file I/O.

/** @param {unknown} value */
export function esc(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

/** The build step replaces the contents of this element with the version from Git tags. */
export const VERSION_PLACEHOLDER = 'Development build';

/**
 * @param {string} name
 * @param {string} [cls]
 * @param {string} [base]
 */
export function icon(name, cls = 'icon', base = '') {
  return `<svg class="${cls}" aria-hidden="true"><use href="${base}assets/icons.svg#${name}"></use></svg>`;
}

/** @param {string[]} items */
const tags = (items) => `<ul class="tags">${items.map((t) => `<li>${esc(t)}</li>`).join('')}</ul>`;

export const ext = 'target="_blank" rel="noopener noreferrer"';

/**
 * @param {any} data
 * @param {{ file: string, title: string, description: string, body: string, base?: string, indexable?: boolean, jsonLd?: object, current?: string, ogType?: string }} page
 */
export function layout(data, page) {
  const { site, nav } = data;
  const base = page.base ?? '';
  const url = site.url + (page.file === 'index.html' ? '' : page.file);
  const indexable = page.indexable ?? true;
  const navItems = nav
    .map(
      (/** @type {{href: string, label: string}} */ n) =>
        `          <li><a href="${base}${n.href}"${n.href === (page.current ?? page.file) ? ' aria-current="page"' : ''}>${esc(n.label)}</a></li>`,
    )
    .join('\n');
  const seo = indexable
    ? `\n    <link rel="canonical" href="${url}" />\n    <meta property="og:url" content="${url}" />`
    : '\n    <meta name="robots" content="noindex" />';
  const ld = page.jsonLd ? `\n    <script type="application/ld+json">${JSON.stringify(page.jsonLd)}</script>` : '';
  return `<!DOCTYPE html>
<!-- Generated by scripts/generate.mjs from data/site.json. Edit the data, then run npm run generate. -->
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${esc(page.title)}</title>
    <meta name="description" content="${esc(page.description)}" />
    <meta name="author" content="${esc(site.name)}" />
    <meta name="theme-color" content="#f5f5f7" media="(prefers-color-scheme: light)" />
    <meta name="theme-color" content="#000000" media="(prefers-color-scheme: dark)" />${seo}
    <meta property="og:type" content="${page.ogType ?? 'website'}" />
    <meta property="og:site_name" content="${esc(site.name)}" />
    <meta property="og:title" content="${esc(page.title)}" />
    <meta property="og:description" content="${esc(page.description)}" />
    <meta property="og:image" content="${site.url}${site.ogImage}" />
    <meta property="og:image:width" content="1200" />
    <meta property="og:image:height" content="630" />
    <meta name="twitter:card" content="summary_large_image" />
    <link rel="icon" href="${base}favicon.svg" type="image/svg+xml" />
    <link rel="apple-touch-icon" href="${base}assets/img/apple-touch-icon.png" />
    <link rel="stylesheet" href="${base}assets/css/site.css" />${ld}
    <script>document.documentElement.classList.add("js");</script>
    <script src="${base}assets/js/site.js" defer></script>
  </head>
  <body>
    <a class="skip-link" href="#main">Skip to content</a>
    <nav class="navbar" id="navbar" aria-label="Main navigation">
      <div class="container">
        <a href="${base}index.html" class="navbar-brand">${esc(site.name)}<span aria-hidden="true">.</span></a>
        <button class="menu-toggle" id="menuToggle" type="button" aria-label="Menu" aria-controls="navbarMenu" aria-expanded="false">
          <span></span><span></span><span></span>
        </button>
        <ul class="navbar-menu" id="navbarMenu">
${navItems}
          <li class="navbar-social">
            <a href="${site.linkedin}" ${ext} aria-label="LinkedIn">${icon('linkedin', 'icon-sm', base)}</a>
            <a href="${site.github}" ${ext} aria-label="GitHub">${icon('github', 'icon-sm', base)}</a>
          </li>
        </ul>
      </div>
    </nav>

    <main id="main">
${page.body}
    </main>

    <footer class="footer">
      <div class="container">
        <ul class="footer-social">
          <li><a href="${site.linkedin}" ${ext} aria-label="LinkedIn">${icon('linkedin', 'icon', base)}</a></li>
          <li><a href="${site.github}" ${ext} aria-label="GitHub">${icon('github', 'icon', base)}</a></li>
          <li><a href="mailto:${site.email}" aria-label="Email">${icon('mail', 'icon', base)}</a></li>
        </ul>
        <p>© 2026 ${esc(site.name)} · <span class="app-version" data-app-version>${VERSION_PLACEHOLDER}</span></p>
      </div>
    </footer>
  </body>
</html>
`;
}

/** @param {string} eyebrow @param {string} h1 @param {string} lead */
